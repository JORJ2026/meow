const KEY='inkbound-settings';
const DEF=Object.fromEntries(SCHEMA.map(s=>[s.key,s.def]));
let V={...DEF};
try{Object.assign(V,JSON.parse(localStorage.getItem(KEY)||'{}'))}catch(e){}
for(const s of SCHEMA){const v=V[s.key];if(s.bool)V[s.key]=typeof v==='boolean'?v:s.def;else V[s.key]=typeof v==='number'&&isFinite(v)?Math.min(s.max,Math.max(s.min,v)):s.def}
function save(){try{localStorage.setItem(KEY,JSON.stringify(V))}catch(e){}}
export const cfg=k=>V[k];
export function setCfg(k,v){const s=SCHEMA.find(x=>x.key===k);if(!s)return;V[k]=s.bool?!!v:Math.min(s.max,Math.max(s.min,+v));save()}
export function resetCfg(){V={...DEF};save()}
